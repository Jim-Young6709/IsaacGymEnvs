def add_polyline(
    server: viser.ViserServer,
    name: str,
    points: np.ndarray,
    color: tuple[int, int, int],
    line_width: float = 2.0,
) -> Optional[object]:
    points = np.asarray(points, dtype=np.float32)
    if points.shape[0] < 2:
        return None
    segments = np.stack([points[:-1], points[1:]], axis=1)
    colors = np.tile(np.asarray(color, dtype=np.uint8), (segments.shape[0], 2, 1))
    return server.scene.add_line_segments(name=name, points=segments, colors=colors, line_width=line_width)


def build_robot_cfg_mapper(viser_joint_names: tuple[str, ...], saved_dof_names: list[str]):
    if saved_dof_names:
        saved_name_to_idx = {name: idx for idx, name in enumerate(saved_dof_names)}
        missing = [name for name in viser_joint_names if name not in saved_name_to_idx]
        if missing:
            print(f"Warning: {len(missing)} Viser joints not found in saved dof_names; filling them with 0.")

        def _map(q_isaac: np.ndarray) -> np.ndarray:
            cfg = np.zeros(len(viser_joint_names), dtype=np.float64)
            for viser_idx, joint_name in enumerate(viser_joint_names):
                saved_idx = saved_name_to_idx.get(joint_name)
                if saved_idx is not None and saved_idx < q_isaac.shape[0]:
                    cfg[viser_idx] = q_isaac[saved_idx]
            return cfg

        return _map

    if len(viser_joint_names) == 32:
        def _map(q_isaac: np.ndarray) -> np.ndarray:
            if q_isaac.shape[0] == 32:
                return q_isaac[ISAAC_TO_VISER_IDX]
            if q_isaac.shape[0] == len(viser_joint_names):
                return q_isaac
            raise ValueError(f"Cannot map robot q shape {q_isaac.shape} to {len(viser_joint_names)} Viser joints.")

        return _map

    def _map(q_isaac: np.ndarray) -> np.ndarray:
        if q_isaac.shape[0] != len(viser_joint_names):
            raise ValueError(f"Cannot map robot q shape {q_isaac.shape} to {len(viser_joint_names)} Viser joints.")
        return q_isaac

    return _map


def get_num_frames(demo: ReplayDemo) -> int:
    num_frames = min(demo.robot_joint_position.shape[0], demo.object_pose.shape[0])
    if num_frames <= 0:
        raise RuntimeError("Trajectory contains no frames.")
    return int(num_frames)


def remove_handles(handles: list[object]) -> None:
    while handles:
        handle = handles.pop()
        try:
            handle.remove()
        except AttributeError:
            pass


def quat_xyzw_to_matrix(quat_xyzw: np.ndarray) -> np.ndarray:
    quat = np.asarray(quat_xyzw, dtype=np.float64).reshape(4)
    norm = np.linalg.norm(quat)
    if norm <= 1e-12:
        return np.eye(3, dtype=np.float64)
    x, y, z, w = quat / norm
    return np.array(
        [
            [1.0 - 2.0 * (y * y + z * z), 2.0 * (x * y - z * w), 2.0 * (x * z + y * w)],
            [2.0 * (x * y + z * w), 1.0 - 2.0 * (x * x + z * z), 2.0 * (y * z - x * w)],
            [2.0 * (x * z - y * w), 2.0 * (y * z + x * w), 1.0 - 2.0 * (x * x + y * y)],
        ],
        dtype=np.float64,
    )


def transform_points_xyzw(points: np.ndarray, pose7_xyzw: np.ndarray) -> np.ndarray:
    points = np.asarray(points, dtype=np.float32).reshape(-1, 3)
    if points.size == 0:
        return points
    pose = np.asarray(pose7_xyzw, dtype=np.float64).reshape(7)
    rotation = quat_xyzw_to_matrix(pose[3:7])
    return (points.astype(np.float64) @ rotation.T + pose[:3]).astype(np.float32)


def sample_box_surface_points(dimensions: np.ndarray, num_points: int) -> np.ndarray:
    dimensions = np.asarray(dimensions, dtype=np.float64).reshape(3)
    num_points = int(num_points)
    if num_points <= 0 or np.any(dimensions <= 0.0):
        return np.zeros((0, 3), dtype=np.float32)

    x, y, z = dimensions
    face_areas = np.asarray([y * z, y * z, x * z, x * z, x * y, x * y], dtype=np.float64)
    if face_areas.sum() <= 0.0:
        return np.zeros((0, 3), dtype=np.float32)

    counts = np.floor(face_areas / face_areas.sum() * num_points).astype(np.int64)
    counts[-1] += num_points - int(counts.sum())
    half = dimensions / 2.0
    samples = []
    for face_idx, count in enumerate(counts):
        if count <= 0:
            continue
        uv = np.random.uniform(-1.0, 1.0, size=(int(count), 2))
        pts = np.zeros((int(count), 3), dtype=np.float64)
        if face_idx == 0:
            pts[:, 0] = half[0]
            pts[:, 1] = uv[:, 0] * half[1]
            pts[:, 2] = uv[:, 1] * half[2]
        elif face_idx == 1:
            pts[:, 0] = -half[0]
            pts[:, 1] = uv[:, 0] * half[1]
            pts[:, 2] = uv[:, 1] * half[2]
        elif face_idx == 2:
            pts[:, 1] = half[1]
            pts[:, 0] = uv[:, 0] * half[0]
            pts[:, 2] = uv[:, 1] * half[2]
        elif face_idx == 3:
            pts[:, 1] = -half[1]
            pts[:, 0] = uv[:, 0] * half[0]
            pts[:, 2] = uv[:, 1] * half[2]
        elif face_idx == 4:
            pts[:, 2] = half[2]
            pts[:, 0] = uv[:, 0] * half[0]
            pts[:, 1] = uv[:, 1] * half[1]
        else:
            pts[:, 2] = -half[2]
            pts[:, 0] = uv[:, 0] * half[0]
            pts[:, 1] = uv[:, 1] * half[1]
        samples.append(pts)
    return np.concatenate(samples, axis=0).astype(np.float32)


def sample_cuboid_scene_points(
    cuboid_dimensions: np.ndarray,
    cuboid_positions: np.ndarray,
    cuboid_quaternions: np.ndarray,
    num_points: int,
) -> np.ndarray:
    cuboid_dimensions = np.asarray(cuboid_dimensions, dtype=np.float64).reshape(-1, 3)
    cuboid_positions = np.asarray(cuboid_positions, dtype=np.float64).reshape(-1, 3)
    cuboid_quaternions = np.asarray(cuboid_quaternions, dtype=np.float64).reshape(-1, 4)
    num_points = int(num_points)
    if num_points <= 0 or cuboid_dimensions.shape[0] == 0:
        return np.zeros((0, 3), dtype=np.float32)

    valid = np.all(cuboid_dimensions > 0.0, axis=1)
    if not np.any(valid):
        return np.zeros((0, 3), dtype=np.float32)

    dims = cuboid_dimensions[valid]
    centers = cuboid_positions[valid]
    quats = cuboid_quaternions[valid]
    areas = 2.0 * (dims[:, 0] * dims[:, 1] + dims[:, 0] * dims[:, 2] + dims[:, 1] * dims[:, 2])
    if areas.sum() <= 0.0:
        return np.zeros((0, 3), dtype=np.float32)

    counts = np.floor(areas / areas.sum() * num_points).astype(np.int64)
    counts[-1] += num_points - int(counts.sum())
    point_sets = []
    for dim, center, quat, count in zip(dims, centers, quats, counts):
        local_points = sample_box_surface_points(dim, int(count))
        if local_points.shape[0] == 0:
            continue
        rotation = quat_xyzw_to_matrix(quat)
        point_sets.append((local_points.astype(np.float64) @ rotation.T + center).astype(np.float32))

    if not point_sets:
        return np.zeros((0, 3), dtype=np.float32)
    points = np.concatenate(point_sets, axis=0)
    if points.shape[0] > num_points:
        points = points[np.random.choice(points.shape[0], num_points, replace=False)]
    return points.astype(np.float32, copy=False)


def finite_xyz(points: np.ndarray) -> np.ndarray:
    points = np.asarray(points, dtype=np.float32).reshape(-1, 3)
    if points.shape[0] == 0:
        return points
    return points[np.isfinite(points).all(axis=1)]


def has_ground_plane_cuboid(demo: ReplayDemo) -> bool:
    dims = np.asarray(demo.cuboid_dimensions, dtype=np.float64).reshape(-1, 3)
    pos = np.asarray(demo.cuboid_positions, dtype=np.float64).reshape(-1, 3)
    if dims.shape[0] == 0:
        return False
    is_thin_floor = dims[:, 2] <= 0.005
    is_large = (dims[:, 0] >= 2.0) & (dims[:, 1] >= 2.0)
    is_near_zero = np.abs(pos[:, 2]) <= 0.02
    return bool(np.any(is_thin_floor & is_large & is_near_zero))


