"""Replay saved env/robot/object trajectories with Viser.

Expected input is an HDF5 generated by pre_sample_env_robot_object_trajectory.py.
Each demo is loaded into memory, then Viser renders:
  - static cuboid obstacles
  - robot URDF trajectory
  - object mesh or object URDF trajectory

Example:
    python IsaacGymEnvs/isaacgymenvs/presampling/replay_env_robot_object_trajectory_viser.py \
        ./presampled_envs/completed/debug_sr_0.1200_num_12.hdf5 --demo 0
"""

