def resolve_torch_device(device_text: str) -> torch.device:
    if device_text == "auto":
        return torch.device("cuda" if torch.cuda.is_available() else "cpu")
    return torch.device(device_text)


def build_torchurdf_joint_mapping(torchurdf_joint_names: tuple[str, ...], saved_dof_names: list[str]) -> Optional[list[int]]:
    if not saved_dof_names:
        return None
    saved_name_to_idx = {name: idx for idx, name in enumerate(saved_dof_names)}
    missing = [name for name in torchurdf_joint_names if name not in saved_name_to_idx]
    if missing:
        raise KeyError(f"{len(missing)} TorchURDF joints not found in saved dof_names: {missing[:5]}")
    return [saved_name_to_idx[name] for name in torchurdf_joint_names]


class PointCloudReplayHelper:
    def __init__(self, demo: ReplayDemo, cfg: PointCloudReplayConfig):
        self.demo = demo
        self.cfg = cfg
        self.device = resolve_torch_device(cfg.device)
        self.static_scene_pcd = self._build_static_scene_pcd()
        self.ground_plane_pcd = self._build_ground_plane_pcd()
        self.object_pcd_local = self._build_object_pcd_local()
        robot_sampler_points = max(int(cfg.num_robot_points), 4096)
        self.robot_sampler = GlorbotSampler(
            urdf_path=demo.robot_urdf_path,
            device=self.device,
            num_points=robot_sampler_points,
        )
        self.robot_filter = GlorbotCollisionChecker(
            urdf_path=str(demo.robot_urdf_path),
            device=self.device,
        )
        self.robot_joint_mapping = build_torchurdf_joint_mapping(
            tuple(self.robot_sampler.robot.actuated_joint_names),
            demo.robot_dof_names,
        )
        self.cache: OrderedDict[int, dict[str, np.ndarray]] = OrderedDict()

    def _build_static_scene_pcd(self) -> np.ndarray:
        if self.demo.scene_pcd_params is not None:
            try:
                return compute_scene_oracle_pcd(
                    self.cfg.num_static_points,
                    *decompose_scene_pcd_params_obs(self.demo.scene_pcd_params),
                ).astype(np.float32)
            except Exception as exc:
                print(f"Warning: failed to sample static PCD from scene params; falling back to cuboids: {exc}")

        return sample_cuboid_scene_points(
            self.demo.cuboid_dimensions,
            self.demo.cuboid_positions,
            self.demo.cuboid_quaternions,
            self.cfg.num_static_points,
        )

    def _build_ground_plane_pcd(self) -> np.ndarray:
        if int(self.cfg.num_distractor_points) <= 0 or has_ground_plane_cuboid(self.demo):
            return np.zeros((0, 3), dtype=np.float32)

        return sample_cuboid_scene_points(
            np.asarray([GROUND_PLANE_DIMENSIONS], dtype=np.float32),
            np.asarray([GROUND_PLANE_POSITION], dtype=np.float32),
            np.asarray([GROUND_PLANE_QUAT_XYZW], dtype=np.float32),
            int(self.cfg.num_distractor_points),
        )

    def _build_object_pcd_local(self) -> np.ndarray:
        if self.demo.object_pcd_local is not None:
            return np.asarray(self.demo.object_pcd_local, dtype=np.float32).reshape(-1, 3)

        if self.demo.object_mesh_path is not None:
            mesh = load_trimesh_mesh(self.demo.object_mesh_path, self.demo.object_scale)
            points = trimesh.sample.sample_surface(mesh, int(self.cfg.num_object_points))[0]
            return points.astype(np.float32)

        return np.zeros((0, 3), dtype=np.float32)

    def _render_point_count(self) -> int:
        if self.cfg.render_points is not None:
            return int(self.cfg.render_points)
        full_count = (
            int(self.cfg.num_static_points)
            + int(self.cfg.num_robot_points)
            + int(self.cfg.num_object_points)
            + int(self.cfg.num_distractor_points)
        )
        return min(10000, full_count)

    def _frame_base_pos(self, frame_idx: int) -> np.ndarray:
        if self.demo.franka_base_pose is not None:
            return self.demo.franka_base_pose[frame_idx, :3].astype(np.float32)
        q = self.demo.robot_joint_position[frame_idx]
        return np.asarray([q[0], q[1], 0.0], dtype=np.float32)

    def _frame_eef_pos(self, frame_idx: int) -> np.ndarray:
        if self.demo.robot_eef_pose is not None:
            return self.demo.robot_eef_pose[frame_idx, :3].astype(np.float32)
        if self.demo.object_center_pos is not None:
            return self.demo.object_center_pos[frame_idx].astype(np.float32)
        return self.demo.object_pose[frame_idx, :3].astype(np.float32)

    def _frame_aux_pos(self, frame_idx: int) -> np.ndarray:
        if self.demo.object_center_pos is not None:
            return self.demo.object_center_pos[frame_idx].astype(np.float32)
        return self._frame_eef_pos(frame_idx)

    def _compute_policy_pcd(self, depth_pcd: torch.Tensor, lidar_pcd: torch.Tensor, frame_idx: int) -> torch.Tensor:
        num_points = torch.tensor(self.cfg.local_points, device=self.device, dtype=torch.int64)
        depth_ratio = float(self.cfg.depth_pcd_ratio)
        depth_counts = (num_points * depth_ratio).to(torch.int64)
        lidar_counts = num_points - depth_counts

        franka_base_pos = torch.as_tensor(self._frame_base_pos(frame_idx), device=self.device).view(1, 3)
        eef_pos = torch.as_tensor(self._frame_eef_pos(frame_idx), device=self.device).view(1, 3)
        aux_pos = torch.as_tensor(self._frame_aux_pos(frame_idx), device=self.device).view(1, 3)
        local_ranges = self.cfg.local_ranges

        local_parts = []
        for key, pcd, counts in (("depth", depth_pcd, depth_counts), ("lidar", lidar_pcd, lidar_counts)):
            base_pcd, _ = crop_local_pcd(
                pcd=pcd,
                local_range=float(local_ranges[0]),
                num_local_points=int(counts[0].item()),
                is_cylindrical=True,
                crop_center=franka_base_pos,
                log_name=f"base{key}",
            )
            local_parts.append(base_pcd)

            if int(counts[1].item()) > 0:
                eef_pcd, _ = crop_local_pcd(
                    pcd=pcd,
                    local_range=float(local_ranges[1]),
                    num_local_points=int(counts[1].item()),
                    is_cylindrical=False,
                    crop_center=eef_pos,
                    log_name=f"eef{key}",
                )
            else:
                eef_pcd = torch.zeros((1, 0, 3), device=self.device, dtype=pcd.dtype)
            local_parts.append(eef_pcd)

            aux_pcd, _ = crop_local_pcd(
                pcd=pcd,
                local_range=float(local_ranges[2]),
                num_local_points=int(counts[2].item()),
                is_cylindrical=False,
                crop_center=aux_pos,
                log_name=f"aux{key}",
            )
            local_parts.append(aux_pcd)

        return torch.cat(
            [
                local_parts[0],
                local_parts[3],
                local_parts[1],
                local_parts[4],
                local_parts[2],
                local_parts[5],
            ],
            dim=1,
        )

    def _add_xyz_noise(self, pcd: torch.Tensor) -> torch.Tensor:
        noise_std = float(self.cfg.xyz_noise_std_m)
        if noise_std <= 0.0 or pcd.numel() == 0:
            return pcd
        finite_mask = torch.isfinite(pcd).all(dim=-1, keepdim=True)
        noise = torch.randn_like(pcd) * noise_std
        return torch.where(finite_mask, pcd + noise, pcd)

    def compute(self, frame_idx: int) -> dict[str, np.ndarray]:
        frame_idx = int(frame_idx)
        if frame_idx in self.cache:
            self.cache.move_to_end(frame_idx)
            return self.cache[frame_idx]

        q = torch.as_tensor(
            self.demo.robot_joint_position[frame_idx : frame_idx + 1],
            device=self.device,
            dtype=torch.float32,
        )
        robot_pcd = self.robot_sampler.sample(
            q,
            self.robot_joint_mapping,
            num_points=int(self.cfg.num_robot_points),
        )
        object_pcd_world = transform_points_xyzw(self.object_pcd_local, self.demo.object_pose[frame_idx])
        scene_parts = [self.static_scene_pcd]
        if self.ground_plane_pcd.shape[0] > 0:
            scene_parts.append(self.ground_plane_pcd)
        if object_pcd_world.shape[0] > 0:
            scene_parts.append(object_pcd_world)
        scene_pcd = np.concatenate(scene_parts, axis=0).astype(np.float32)
        scene_pcd_t = torch.as_tensor(scene_pcd, device=self.device, dtype=torch.float32).unsqueeze(0)
        gt_pcd = torch.cat([scene_pcd_t, robot_pcd], dim=1)

        num_render_points = self._render_point_count()
        if self.demo.camera_pose is not None:
            camera_pose = torch.as_tensor(
                self.demo.camera_pose[frame_idx : frame_idx + 1],
                device=self.device,
                dtype=torch.float32,
            )
            depth_pcd, _ = simulate_depth_cam_render_from_pose(
                pcd=gt_pcd,
                camera_pose=camera_pose,
                num_points=num_render_points,
                jitter_std_m=float(self.cfg.depth_jitter_std_m),
                use_compile=False,
            )
        else:
            depth_pcd = torch.zeros((1, 0, 3), device=self.device, dtype=torch.float32)

        if self.demo.lidar_pose is not None:
            lidar_pose = torch.as_tensor(
                self.demo.lidar_pose[frame_idx : frame_idx + 1],
                device=self.device,
                dtype=torch.float32,
            )
            raw_lidar_pcd, _ = simulate_lidar_render_from_pose(
                pcd=gt_pcd,
                lidar_pose=lidar_pose,
                num_points=num_render_points,
                num_azimuth=int(self.cfg.lidar_azimuth),
                num_polar=int(self.cfg.lidar_polar),
                suppress_bins=int(self.cfg.lidar_suppress_bins),
                jitter_std_m=float(self.cfg.lidar_jitter_std_m),
                use_compile=False,
            )
            policy_lidar_pcd = self.robot_filter.filter_pointcloud_outside_spheres(
                pointclouds=raw_lidar_pcd,
                joint_angles=q,
                joint_mapping_list=self.robot_joint_mapping,
            )
        else:
            raw_lidar_pcd = torch.zeros((1, 0, 3), device=self.device, dtype=torch.float32)
            policy_lidar_pcd = raw_lidar_pcd

        policy_input_pcd = self._compute_policy_pcd(depth_pcd, policy_lidar_pcd, frame_idx)
        raw_lidar_pcd_display = self._add_xyz_noise(raw_lidar_pcd)
        depth_pcd_display = self._add_xyz_noise(depth_pcd)
        policy_input_pcd_display = self._add_xyz_noise(policy_input_pcd)

        clouds = {
            "ground_truth": gt_pcd[0][::16].detach().cpu().numpy(),
            "raw_lidar": raw_lidar_pcd_display[0].detach().cpu().numpy(),
            "raw_depth": depth_pcd_display[0].detach().cpu().numpy(),
            "policy_input": policy_input_pcd_display[0].detach().cpu().numpy(),
        }
        if self.cfg.cache_size > 0:
            self.cache[frame_idx] = clouds
            self.cache.move_to_end(frame_idx)
            while len(self.cache) > int(self.cfg.cache_size):
                self.cache.popitem(last=False)
        return clouds


def create_viewer(
    hdf5_path: Path,
    initial_demo: str,
    robot_urdf_override: Optional[str],
    host: str,
    port: int,
    fps: float,
    pcd_config: PointCloudReplayConfig,
) -> None:
    hdf5_path = hdf5_path.expanduser().resolve()
    demo_keys = list_demo_keys(hdf5_path)
    initial_demo_idx = resolve_demo_index(demo_keys, initial_demo)
    demo = load_replay_demo(hdf5_path, demo_keys[initial_demo_idx], robot_urdf_override)
    num_frames = get_num_frames(demo)

    server = viser.ViserServer(host=host, port=port)
    server.gui.configure_theme(control_width="medium")
    server.scene.add_frame("/WorldAxes", show_axes=True, axes_length=0.25, axes_radius=0.01)
    server.scene.add_grid("/grid", width=6.0, height=6.0, position=(0.0, 0.0, 0.0), shadow_opacity=0.15)
    ground_plane_handle = add_ground_plane(server)

    server.scene.add_frame("/robot", show_axes=False)
    robot_urdf = ViserUrdf(
        server,
        urdf_or_path=demo.robot_urdf_path,
        root_node_name="/robot",
        load_meshes=True,
        load_collision_meshes=False,
    )
    robot_joint_names = robot_urdf.get_actuated_joint_names()
    map_robot_cfg = build_robot_cfg_mapper(robot_joint_names, demo.robot_dof_names)

    object_root = server.scene.add_frame("/object", show_axes=False)

    demo_index_handle = server.gui.add_number(
        "Demo",
        initial_value=float(initial_demo_idx),
        min=0.0,
        max=float(len(demo_keys) - 1),
        step=1.0,
    )
    previous_demo_button = server.gui.add_button("Previous Demo")
    next_demo_button = server.gui.add_button("Next Demo")
    frame_slider = server.gui.add_slider(
        "Frame",
        min=0,
        max=max(num_frames - 1, 1),
        step=1,
        initial_value=0,
        disabled=(num_frames == 1),
    )
    fps_handle = server.gui.add_number("FPS", initial_value=float(fps), min=1.0, max=240.0, step=1.0)
    loop_handle = server.gui.add_checkbox("Loop", initial_value=False)
    replay_button = server.gui.add_button("Replay")
    ground_plane_visible_handle = server.gui.add_checkbox("Ground Plane", initial_value=True)

    @ground_plane_visible_handle.on_update
    def _(_) -> None:
        ground_plane_handle.visible = bool(ground_plane_visible_handle.value)

    pcd_handles: dict[str, object] = {}
    pcd_visible_handles: dict[str, object] = {}
    pcd_point_size_handle = None
    pcd_point_shape_handle = None
    if pcd_config.enabled:
        pcd_handles = add_point_cloud_visuals(server, pcd_config.point_size, pcd_config.point_shape)
        pcd_visible_handles = {
            "ground_truth": server.gui.add_checkbox("GT PCD", initial_value=True),
            "raw_lidar": server.gui.add_checkbox("Raw Lidar PCD", initial_value=True),
            "raw_depth": server.gui.add_checkbox("Raw Depth PCD", initial_value=True),
            "policy_input": server.gui.add_checkbox("Policy Input PCD", initial_value=True),
        }
        pcd_point_size_handle = server.gui.add_number(
            "PCD Point Size",
            initial_value=float(pcd_config.point_size),
            min=0.0005,
            max=0.05,
            step=0.0005,
        )
        pcd_point_shape_handle = server.gui.add_dropdown(
            "PCD Point Shape",
            options=PCD_POINT_SHAPES,
            initial_value=pcd_config.point_shape,
        )

    frame_lock = threading.RLock()
    replay_lock = threading.Lock()

    def make_pointcloud_helper(current_demo: ReplayDemo) -> Optional[PointCloudReplayHelper]:
        if not pcd_config.enabled:
            return None
        try:
            return PointCloudReplayHelper(current_demo, pcd_config)
        except Exception as exc:
            print(f"Warning: point-cloud visualization disabled for {current_demo.demo_key}: {exc}")
            return None

    state = {
        "demo": demo,
        "demo_idx": initial_demo_idx,
        "num_frames": num_frames,
        "map_robot_cfg": map_robot_cfg,
        "scene_handles": [],
        "object_handles": [],
        "object_urdf": None,
        "eef_frame": None,
        "object_source": "",
        "generation": 0,
        "loading_demo": False,
        "robot_urdf_path": demo.robot_urdf_path,
        "pointcloud_helper": make_pointcloud_helper(demo),
        "pcd_error_reported": False,
    }

    def set_empty_pointclouds() -> None:
        for handle in pcd_handles.values():
            handle.points = np.zeros((0, 3), dtype=np.float16)

    def update_pointcloud_visibility() -> None:
        for cloud_name, handle in pcd_handles.items():
            visible_handle = pcd_visible_handles.get(cloud_name)
            if visible_handle is not None:
                handle.visible = bool(visible_handle.value)

    def update_point_clouds(frame_idx: int) -> None:
        if not pcd_handles:
            return
        update_pointcloud_visibility()
        if not any(bool(handle.value) for handle in pcd_visible_handles.values()):
            return

        pointcloud_helper = state["pointcloud_helper"]
        if pointcloud_helper is None:
            set_empty_pointclouds()
            return

        try:
            clouds = pointcloud_helper.compute(frame_idx)
        except Exception as exc:
            if not bool(state["pcd_error_reported"]):
                print(f"Warning: failed to update point clouds for {state['demo'].demo_key}: {exc}")
                state["pcd_error_reported"] = True
            set_empty_pointclouds()
            return

        for cloud_name, handle in pcd_handles.items():
            if not bool(pcd_visible_handles[cloud_name].value):
                continue
            handle.points = finite_xyz(clouds.get(cloud_name, np.zeros((0, 3), dtype=np.float32)))

    for cloud_name, visible_handle in pcd_visible_handles.items():
        @visible_handle.on_update
        def _(_, cloud_name=cloud_name) -> None:
            pcd_handles[cloud_name].visible = bool(pcd_visible_handles[cloud_name].value)
            if bool(pcd_visible_handles[cloud_name].value):
                update_point_clouds(int(frame_slider.value))

    if pcd_point_size_handle is not None:
        @pcd_point_size_handle.on_update
        def _(_) -> None:
            for handle in pcd_handles.values():
                handle.point_size = float(pcd_point_size_handle.value)

    if pcd_point_shape_handle is not None:
        @pcd_point_shape_handle.on_update
        def _(_) -> None:
            for handle in pcd_handles.values():
                handle.point_shape = str(pcd_point_shape_handle.value)

    def update_demo_buttons() -> None:
        demo_idx = int(state["demo_idx"])
        previous_demo_button.disabled = demo_idx <= 0
        next_demo_button.disabled = demo_idx >= len(demo_keys) - 1

    def reload_dynamic_scene() -> None:
        demo = state["demo"]
        num_frames = int(state["num_frames"])

        remove_handles(state["scene_handles"])
        remove_handles(state["object_handles"])
        object_urdf = state["object_urdf"]
        if object_urdf is not None:
            object_urdf.remove()
            state["object_urdf"] = None

        if demo.object_urdf_path is not None:
            state["object_urdf"] = ViserUrdf(
                server,
                urdf_or_path=demo.object_urdf_path,
                root_node_name="/object",
                load_meshes=True,
                load_collision_meshes=False,
            )
            object_source = f"URDF: {demo.object_urdf_path}"
        elif demo.object_mesh_path is not None:
            object_mesh = load_trimesh_mesh(demo.object_mesh_path, demo.object_scale)
            state["object_handles"].append(server.scene.add_mesh_trimesh("/object/mesh", mesh=object_mesh))
            object_source = f"mesh: {demo.object_mesh_path}"
        else:
            state["object_handles"].append(
                server.scene.add_icosphere("/object/placeholder", radius=0.025, color=(230, 130, 60))
            )
            object_source = "placeholder: object_info mesh path was unavailable"

        state["scene_handles"].extend(add_cuboid_obstacles(server, demo))
        state["scene_handles"].extend(add_compartment_state(server, demo))
        object_path = add_polyline(
            server,
            "/paths/object_center",
            demo.object_pose[:num_frames, :3],
            (235, 120, 40),
            2.0,
        )
        if object_path is not None:
            state["scene_handles"].append(object_path)

        if demo.robot_eef_pose is not None:
            eef_path = add_polyline(
                server,
                "/paths/eef",
                demo.robot_eef_pose[:num_frames, :3],
                (40, 120, 240),
                2.0,
            )
            if eef_path is not None:
                state["scene_handles"].append(eef_path)
            eef_frame = server.scene.add_frame("/eef", show_axes=True, axes_length=0.08, axes_radius=0.004)
            state["scene_handles"].append(eef_frame)
            state["eef_frame"] = eef_frame
        else:
            state["eef_frame"] = None

        state["object_source"] = object_source

    def update_frame(frame_idx: int, update_slider: bool = True) -> None:
        with frame_lock:
            demo = state["demo"]
            num_frames = int(state["num_frames"])
            frame_idx = int(np.clip(frame_idx, 0, num_frames - 1))
            robot_urdf.update_cfg(state["map_robot_cfg"](demo.robot_joint_position[frame_idx]))

            object_pose = demo.object_pose[frame_idx]
            object_root.position = tuple(float(v) for v in object_pose[:3])
            object_root.wxyz = xyzw_to_wxyz(object_pose[3:7])

            eef_frame = state["eef_frame"]
            if eef_frame is not None and demo.robot_eef_pose is not None:
                eef_pose = demo.robot_eef_pose[frame_idx]
                eef_frame.position = tuple(float(v) for v in eef_pose[:3])
                eef_frame.wxyz = xyzw_to_wxyz(eef_pose[3:7])

            update_point_clouds(frame_idx)

            if update_slider and int(frame_slider.value) != frame_idx:
                frame_slider.value = frame_idx

    def load_demo_by_index(new_demo_idx: int) -> None:
        new_demo_idx = int(np.clip(new_demo_idx, 0, len(demo_keys) - 1))
        if new_demo_idx == int(state["demo_idx"]):
            state["loading_demo"] = True
            try:
                demo_index_handle.value = float(new_demo_idx)
            finally:
                state["loading_demo"] = False
            update_demo_buttons()
            return

        new_demo = load_replay_demo(hdf5_path, demo_keys[new_demo_idx], robot_urdf_override)
        new_num_frames = get_num_frames(new_demo)
        new_pointcloud_helper = make_pointcloud_helper(new_demo)
        if new_demo.robot_urdf_path != state["robot_urdf_path"]:
            print(
                "Warning: selected demo has a different robot URDF; "
                f"continuing with {state['robot_urdf_path']}."
            )

        with frame_lock:
            state["generation"] = int(state["generation"]) + 1
            state["demo"] = new_demo
            state["demo_idx"] = new_demo_idx
            state["num_frames"] = new_num_frames
            state["map_robot_cfg"] = build_robot_cfg_mapper(robot_joint_names, new_demo.robot_dof_names)
            state["pointcloud_helper"] = new_pointcloud_helper
            state["pcd_error_reported"] = False
            reload_dynamic_scene()

            frame_slider.max = max(new_num_frames - 1, 1)
            frame_slider.disabled = new_num_frames == 1
            state["loading_demo"] = True
            try:
                demo_index_handle.value = float(new_demo_idx)
                frame_slider.value = 0
            finally:
                state["loading_demo"] = False
            update_demo_buttons()
            update_frame(0, update_slider=False)

        print(
            f"Loaded {new_demo.demo_key} ({new_demo_idx + 1}/{len(demo_keys)}), "
            f"frames={new_num_frames}, object source: {state['object_source']}"
        )

    @demo_index_handle.on_update
    def _(_) -> None:
        if bool(state["loading_demo"]):
            return
        load_demo_by_index(int(round(float(demo_index_handle.value))))

    @previous_demo_button.on_click
    def _(_) -> None:
        load_demo_by_index(int(state["demo_idx"]) - 1)

    @next_demo_button.on_click
    def _(_) -> None:
        load_demo_by_index(int(state["demo_idx"]) + 1)

    @frame_slider.on_update
    def _(_) -> None:
        update_frame(int(frame_slider.value), update_slider=False)

    def replay_once() -> None:
        with replay_lock:
            replay_button.disabled = True
            generation = int(state["generation"])
            try:
                while True:
                    num_frames = int(state["num_frames"])
                    for frame_idx in range(num_frames):
                        if generation != int(state["generation"]):
                            return
                        update_frame(frame_idx)
                        time.sleep(1.0 / max(float(fps_handle.value), 1.0))
                    if generation != int(state["generation"]):
                        return
                    if not bool(loop_handle.value):
                        break
            finally:
                replay_button.disabled = False

    @replay_button.on_click
    def _(_) -> None:
        thread = threading.Thread(target=replay_once, name="ViserReplay", daemon=True)
        thread.start()

    @server.on_client_connect
    def _(client: viser.ClientHandle) -> None:
        client.camera.position = (-1.4, -1.4, 1.0)
        client.camera.look_at = (0.3, 0.0, 0.35)

    reload_dynamic_scene()
    update_demo_buttons()
    update_frame(0)
    print(f"Viser replay server: http://{host}:{port}")
    print(f"HDF5: {hdf5_path}")
    print(f"Demo: {demo.demo_key} ({initial_demo_idx + 1}/{len(demo_keys)}), frames={num_frames}")
    print(f"Robot URDF: {demo.robot_urdf_path}")
    print(f"Object source: {state['object_source']}")
    if pcd_config.enabled:
        pointcloud_helper = state["pointcloud_helper"]
        pcd_device = pointcloud_helper.device if pointcloud_helper is not None else pcd_config.device
        print(
            "Point clouds: GT, raw lidar, raw depth, policy input "
            f"(device={pcd_device}, render_points={pcd_config.render_points or 'auto'})"
        )
    print("Use 'Previous Demo'/'Next Demo' to switch demos, then click 'Replay' to play the trajectory.")

    while True:
        time.sleep(10.0)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Replay a saved robot/object trajectory HDF5 in Viser.")
    parser.add_argument("hdf5_path", type=Path, help="Trajectory HDF5 generated by the presampling script.")
    parser.add_argument("--demo", default="0", help="Demo index or key, e.g. 0 or demo_0.")
    parser.add_argument("--host", default="0.0.0.0", help="Viser server host.")
    parser.add_argument("--port", type=int, default=8080, help="Viser server port.")
    parser.add_argument("--fps", type=float, default=60.0, help="Replay speed.")
    parser.add_argument("--robot-urdf", default=None, help="Optional robot URDF path override.")
    parser.add_argument("--no-pointclouds", action="store_true", help="Disable point-cloud reconstruction.")
    parser.add_argument("--pcd-device", default="auto", choices=("auto", "cpu", "cuda"), help="Torch device for PCD reconstruction.")
    parser.add_argument("--pcd-static-points", type=int, default=DISTILLATION_NUM_STATIC_POINTS, help="Static scene points for GT reconstruction.")
    parser.add_argument("--pcd-robot-points", type=int, default=DISTILLATION_NUM_ROBOT_POINTS, help="Robot surface points for GT reconstruction.")
    parser.add_argument("--pcd-object-points", type=int, default=DISTILLATION_NUM_OBJECT_POINTS, help="Object points when object_pcd_local is absent.")
    parser.add_argument("--pcd-distractor-points", type=int, default=DISTILLATION_NUM_DISTRACTOR_POINTS, help="Ground-plane point samples and distractor count used for auto render point cap.")
    parser.add_argument("--pcd-render-points", type=int, default=DISTILLATION_RENDER_POINTS, help="Raw rendered points per sensor; default matches preprocessing cap.")
    parser.add_argument(
        "--pcd-local-points",
        type=int,
        nargs=3,
        default=DISTILLATION_LOCAL_POINTS,
        metavar=("BASE", "EEF", "AUX"),
        help="Policy local_pcd_t point counts before depth/lidar split.",
    )
    parser.add_argument(
        "--pcd-local-range",
        type=float,
        nargs=3,
        default=DISTILLATION_LOCAL_RANGES,
        metavar=("BASE", "EEF", "AUX"),
        help="Policy local_pcd_t crop ranges.",
    )
    parser.add_argument("--pcd-depth-ratio", type=float, default=DISTILLATION_DEPTH_PCD_RATIO, help="Fraction of local policy points drawn from depth PCD.")
    parser.add_argument("--pcd-lidar-azimuth", type=int, default=DISTILLATION_LIDAR_AZIMUTH, help="Rendered lidar azimuth bins.")
    parser.add_argument("--pcd-lidar-polar", type=int, default=DISTILLATION_LIDAR_POLAR, help="Rendered lidar polar bins.")
    parser.add_argument("--pcd-lidar-suppress-bins", type=int, default=DISTILLATION_LIDAR_SUPPRESS_BINS, help="Rendered lidar suppression neighborhood.")
    parser.add_argument("--pcd-lidar-jitter", type=float, default=DISTILLATION_LIDAR_JITTER_STD_M, help="Rendered lidar jitter in meters.")
    parser.add_argument("--pcd-depth-jitter", type=float, default=DISTILLATION_DEPTH_JITTER_STD_M, help="Rendered depth jitter in meters.")
    parser.add_argument("--pcd-noise-std", type=float, default=0.005, help="Gaussian XYZ noise std in meters for rendered depth, raw lidar, and policy-input PCDs.")
    parser.add_argument("--pcd-point-size", type=float, default=0.005, help="Initial Viser point size for PCD overlays.")
    parser.add_argument(
        "--pcd-point-shape",
        choices=PCD_POINT_SHAPES,
        default=DEFAULT_PCD_POINT_SHAPE,
        help="Viser sprite shape for PCD overlays; circle gives rounded points instead of square splats.",
    )
    parser.add_argument("--pcd-cache-size", type=int, default=64, help="Number of frame PCD results to keep in memory.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    pcd_config = PointCloudReplayConfig(
        enabled=not args.no_pointclouds,
        device=args.pcd_device,
        num_static_points=args.pcd_static_points,
        num_robot_points=args.pcd_robot_points,
        num_object_points=args.pcd_object_points,
        num_distractor_points=args.pcd_distractor_points,
        render_points=args.pcd_render_points,
        local_points=tuple(int(v) for v in args.pcd_local_points),
        local_ranges=tuple(float(v) for v in args.pcd_local_range),
        depth_pcd_ratio=float(args.pcd_depth_ratio),
        lidar_azimuth=args.pcd_lidar_azimuth,
        lidar_polar=args.pcd_lidar_polar,
        lidar_suppress_bins=args.pcd_lidar_suppress_bins,
        lidar_jitter_std_m=args.pcd_lidar_jitter,
        depth_jitter_std_m=args.pcd_depth_jitter,
        xyz_noise_std_m=args.pcd_noise_std,
        point_size=args.pcd_point_size,
        point_shape=args.pcd_point_shape,
        cache_size=args.pcd_cache_size,
    )
    create_viewer(
        args.hdf5_path,
        initial_demo=args.demo,
        robot_urdf_override=args.robot_urdf,
        host=args.host,
        port=args.port,
        fps=args.fps,
        pcd_config=pcd_config,
    )


if __name__ == "__main__":
    main()
