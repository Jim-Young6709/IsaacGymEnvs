@dataclass
class ReplayDemo:
    hdf5_path: Path
    demo_key: str
    robot_joint_position: np.ndarray
    robot_eef_pose: Optional[np.ndarray]
    object_pose: np.ndarray
    cuboid_dimensions: np.ndarray
    cuboid_positions: np.ndarray
    cuboid_quaternions: np.ndarray
    compartment_size: Optional[np.ndarray]
    compartment_position: Optional[np.ndarray]
    compartment_quaternion: Optional[np.ndarray]
    robot_urdf_path: Path
    robot_dof_names: list[str]
    object_urdf_path: Optional[Path]
    object_mesh_path: Optional[Path]
    object_scale: Optional[np.ndarray]


def xyzw_to_wxyz(quat_xyzw: np.ndarray) -> tuple[float, float, float, float]:
    quat = np.asarray(quat_xyzw, dtype=np.float64).reshape(4)
    return (float(quat[3]), float(quat[0]), float(quat[1]), float(quat[2]))


def _decode_string(value) -> str:
    if isinstance(value, bytes):
        return value.decode("utf-8")
    if isinstance(value, np.bytes_):
        return value.tobytes().decode("utf-8")
    if isinstance(value, np.ndarray) and value.shape == ():
        return _decode_string(value.item())
    return str(value)


def _decode_string_array(value) -> list[str]:
    array = np.asarray(value)
    return [_decode_string(v) for v in array.reshape(-1)]


def read_optional_string(group: h5py.Group, path: str, default: str = "") -> str:
    try:
        dataset = group[path]
    except KeyError:
        return default
    return _decode_string(dataset[()])


def read_optional_array(group: h5py.Group, path: str) -> Optional[np.ndarray]:
    try:
        dataset = group[path]
    except KeyError:
        return None
    return np.asarray(dataset[()])


def candidate_repo_relative_paths(path: Path) -> list[Path]:
    # CODEX: Support stale absolute paths such as /home/jimyoung/Dex/IsaacGymEnvs/meshes_final/...
    candidates = []
    parts = path.parts
    for anchor in REPO_PATH_ANCHORS:
        if anchor not in parts:
            continue
        anchor_idx = parts.index(anchor)
        suffix_parts = parts[anchor_idx + 1:]
        if not suffix_parts:
            continue
        candidates.append((ISAACGYM_ROOT / Path(*suffix_parts)).resolve())
        candidates.append((REPO_ROOT / anchor / Path(*suffix_parts)).resolve())
    return candidates


def resolve_path(path_text: str, hdf5_path: Path) -> Optional[Path]:
    if not path_text:
        return None

    path = Path(path_text).expanduser()
    if path.is_absolute():
        if path.exists():
            return path
        # CODEX: Prefer local repo copies when absolute paths point at another user's checkout.
        for candidate in candidate_repo_relative_paths(path):
            if candidate.exists():
                return candidate
        return path

    for base in (Path.cwd(), hdf5_path.parent, ISAACGYM_ROOT, REPO_ROOT):
        candidate = (base / path).resolve()
        if candidate.exists():
            return candidate
    return (Path.cwd() / path).resolve()


def demo_sort_key(name: str):
    if name.startswith("demo_") and name[5:].isdigit():
        return int(name[5:])
    return name


def list_demo_keys(hdf5_path: Path) -> list[str]:
    hdf5_path = hdf5_path.expanduser().resolve()
    with h5py.File(hdf5_path, "r") as hdf5_file:
        root = hdf5_file["data"] if "data" in hdf5_file else hdf5_file
        demo_names = sorted(
            (name for name in root.keys() if name.startswith("demo_")),
            key=demo_sort_key,
        )
    if not demo_names:
        raise RuntimeError("No demo_* groups found in HDF5.")
    return demo_names


def resolve_demo_index(demo_keys: list[str], demo: str) -> int:
    if demo.startswith("demo_"):
        if demo not in demo_keys:
            raise KeyError(f"Demo '{demo}' not found. Available examples: {demo_keys[:5]}")
        return demo_keys.index(demo)

    demo_idx = int(demo)
    if demo_idx < 0 or demo_idx >= len(demo_keys):
        raise IndexError(f"Demo index {demo_idx} out of range [0, {len(demo_keys) - 1}].")
    return demo_idx


def get_demo_group(hdf5_file: h5py.File, demo: str) -> tuple[str, h5py.Group]:
    root = hdf5_file["data"] if "data" in hdf5_file else hdf5_file
    demo_names = sorted(
        (name for name in root.keys() if name.startswith("demo_")),
        key=demo_sort_key,
    )
    if not demo_names:
        raise RuntimeError("No demo_* groups found in HDF5.")

    if demo.startswith("demo_"):
        demo_key = demo
    else:
        demo_idx = int(demo)
        if demo_idx < 0 or demo_idx >= len(demo_names):
            raise IndexError(f"Demo index {demo_idx} out of range [0, {len(demo_names) - 1}].")
        demo_key = demo_names[demo_idx]

    if demo_key not in root:
        raise KeyError(f"Demo '{demo_key}' not found. Available examples: {demo_names[:5]}")
    return demo_key, root[demo_key]


def read_compartment_state(demo_group: h5py.Group) -> tuple[Optional[np.ndarray], Optional[np.ndarray], Optional[np.ndarray]]:
    size = read_optional_array(demo_group, "compartment_state/size_xyz")
    position = read_optional_array(demo_group, "compartment_state/position_xyz")
    quaternion = read_optional_array(demo_group, "compartment_state/quaternion_xyzw")
    if size is not None and position is not None and quaternion is not None:
        return (
            np.asarray(size, dtype=np.float64).reshape(3),
            np.asarray(position, dtype=np.float64).reshape(3),
            np.asarray(quaternion, dtype=np.float64).reshape(4),
        )

    raw = read_optional_array(demo_group, "compartment_states")
    if raw is None:
        raw = read_optional_array(demo_group, "environment/compartment_states")
    if raw is not None:
        raw = np.asarray(raw, dtype=np.float64)
        if raw.ndim > 1:
            raw = raw[0]
        raw = raw.reshape(-1)
        if raw.shape[0] >= 10:
            return raw[:3], raw[3:6], raw[6:10]

    size = read_optional_array(demo_group, "environment/box_dimensions_xyz")
    bottom_position = read_optional_array(demo_group, "environment/box_bottom_position_xyz")
    quaternion = read_optional_array(demo_group, "environment/box_quaternion_xyzw")
    if size is not None and bottom_position is not None and quaternion is not None:
        size = np.asarray(size, dtype=np.float64).reshape(3)
        position = np.asarray(bottom_position, dtype=np.float64).reshape(3)
        position[2] += size[2] / 2.0
        return size, position, np.asarray(quaternion, dtype=np.float64).reshape(4)

    return None, None, None


def load_replay_demo(hdf5_path: Path, demo: str, robot_urdf_override: Optional[str]) -> ReplayDemo:
    hdf5_path = hdf5_path.expanduser().resolve()
    with h5py.File(hdf5_path, "r") as hdf5_file:
        demo_key, demo_group = get_demo_group(hdf5_file, demo)

        robot_joint_position = np.asarray(
            demo_group["robot_trajectory/joint_position"][()],
            dtype=np.float64,
        )
        robot_eef_pose = read_optional_array(demo_group, "robot_trajectory/eef_pose7_xyzw")
        if robot_eef_pose is not None:
            robot_eef_pose = np.asarray(robot_eef_pose, dtype=np.float64)

        object_pose_data = read_optional_array(demo_group, "object_trajectory/pose7_xyzw")
        if object_pose_data is None:
            object_pose = np.asarray(demo_group["object_trajectory/root_state"][()][:, :7], dtype=np.float64)
        else:
            object_pose = np.asarray(object_pose_data, dtype=np.float64)

        cuboids = demo_group["obstacles/cuboids"]
        cuboid_dimensions = np.asarray(cuboids["dimensions_xyz"][()], dtype=np.float64)
        cuboid_positions = np.asarray(cuboids["position_xyz"][()], dtype=np.float64)
        cuboid_quaternions = np.asarray(cuboids["quaternion_xyzw"][()], dtype=np.float64)
        compartment_size, compartment_position, compartment_quaternion = read_compartment_state(demo_group)

        saved_robot_urdf = read_optional_string(demo_group, "robot_info/urdf_path")
        robot_urdf_path = resolve_path(robot_urdf_override or saved_robot_urdf, hdf5_path)
        if robot_urdf_path is None or not robot_urdf_path.exists():
            robot_urdf_path = FALLBACK_ROBOT_URDF
        if not robot_urdf_path.exists():
            raise FileNotFoundError(f"Robot URDF not found: {robot_urdf_path}")

        robot_dof_names = []
        robot_dof_names_data = read_optional_array(demo_group, "robot_info/dof_names")
        if robot_dof_names_data is not None:
            robot_dof_names = _decode_string_array(robot_dof_names_data)

        object_urdf_path = resolve_path(read_optional_string(demo_group, "object_info/urdf_path"), hdf5_path)
        if object_urdf_path is not None and not object_urdf_path.exists():
            object_urdf_path = None

        object_mesh_path = resolve_path(read_optional_string(demo_group, "object_info/mesh_path"), hdf5_path)
        if object_mesh_path is not None and not object_mesh_path.exists():
            object_mesh_path = None

        object_scale = read_optional_array(demo_group, "object_info/scale_xyz")
        if object_scale is None:
            object_scale = read_optional_array(demo_group, "object_info/returned_scale")
        if object_scale is not None:
            object_scale = np.asarray(object_scale, dtype=np.float64).reshape(-1)

    return ReplayDemo(
        hdf5_path=hdf5_path,
        demo_key=demo_key,
        robot_joint_position=robot_joint_position,
        robot_eef_pose=robot_eef_pose,
        object_pose=object_pose,
        cuboid_dimensions=cuboid_dimensions,
        cuboid_positions=cuboid_positions,
        cuboid_quaternions=cuboid_quaternions,
        compartment_size=compartment_size,
        compartment_position=compartment_position,
        compartment_quaternion=compartment_quaternion,
        robot_urdf_path=robot_urdf_path,
        robot_dof_names=robot_dof_names,
        object_urdf_path=object_urdf_path,
        object_mesh_path=object_mesh_path,
        object_scale=object_scale,
    )


def load_trimesh_mesh(mesh_path: Path, scale: Optional[np.ndarray]) -> trimesh.Trimesh:
    mesh = trimesh.load(mesh_path, force="mesh")
    if isinstance(mesh, trimesh.Scene):
        mesh = mesh.dump(concatenate=True)
    if not isinstance(mesh, trimesh.Trimesh):
        raise TypeError(f"Could not load a trimesh.Trimesh from {mesh_path}")

    if scale is not None:
        if scale.size == 1:
            mesh.apply_scale(float(scale[0]))
        elif scale.size == 3:
            mesh.apply_scale(scale.astype(np.float64))
        else:
            raise ValueError(f"Object scale must be scalar or xyz, got shape {scale.shape}")
    # CODEX: Override saved mesh materials/textures so replayed objects render red.
    if len(mesh.faces) > 0:
        mesh.visual.face_colors = np.tile(
            np.asarray(OBJECT_MESH_RGBA, dtype=np.uint8),
            (len(mesh.faces), 1),
        )
    elif len(mesh.vertices) > 0:
        mesh.visual.vertex_colors = np.tile(
            np.asarray(OBJECT_MESH_RGBA, dtype=np.uint8),
            (len(mesh.vertices), 1),
        )
    return mesh


def add_cuboid_obstacles(server: viser.ViserServer, demo: ReplayDemo) -> list[object]:
    handles = []
    for idx, (dims, pos, quat) in enumerate(
        zip(demo.cuboid_dimensions, demo.cuboid_positions, demo.cuboid_quaternions)
    ):
        handles.append(
            server.scene.add_box(
                name=f"/scene/cuboid_{idx}",
                dimensions=tuple(float(v) for v in dims),
                position=tuple(float(v) for v in pos),
                wxyz=xyzw_to_wxyz(quat),
                color=(145, 220, 165),
                opacity=0.9,
            )
        )
    return handles


def add_compartment_state(
    server: viser.ViserServer,
    demo: ReplayDemo,
    show_compartment_frame: bool,
) -> list[object]:
    if (
        demo.compartment_size is None
        or demo.compartment_position is None
        or demo.compartment_quaternion is None
    ):
        return []

    handles = [
        server.scene.add_box(
            name="/scene/compartment_state",
            dimensions=tuple(float(v) for v in demo.compartment_size),
            position=tuple(float(v) for v in demo.compartment_position),
            wxyz=xyzw_to_wxyz(demo.compartment_quaternion),
            color=(255, 35, 35),
            opacity=0.23,
        ),
    ]
    if show_compartment_frame:
        # CODEX: Keep the compartment axes opt-in so the default replay view is uncluttered.
        handles.append(
            server.scene.add_frame(
                "/scene/compartment_state_frame",
                position=tuple(float(v) for v in demo.compartment_position),
                wxyz=xyzw_to_wxyz(demo.compartment_quaternion),
                show_axes=True,
                axes_length=0.12,
                axes_radius=0.004,
            )
        )
    return handles


def add_polyline(
    server: viser.ViserServer,
    name: str,
    points: np.ndarray,
    color: tuple[int, int, int],
    line_width: float = 2.0,
) -> Optional[object]:
    points = np.asarray(points, dtype=np.float32)
    if points.shape[0] < 2:
        return None
    segments = np.stack([points[:-1], points[1:]], axis=1)
    colors = np.tile(np.asarray(color, dtype=np.uint8), (segments.shape[0], 2, 1))
    return server.scene.add_line_segments(name=name, points=segments, colors=colors, line_width=line_width)


def build_robot_cfg_mapper(viser_joint_names: tuple[str, ...], saved_dof_names: list[str]):
    if saved_dof_names:
        saved_name_to_idx = {name: idx for idx, name in enumerate(saved_dof_names)}
        missing = [name for name in viser_joint_names if name not in saved_name_to_idx]
        if missing:
            print(f"Warning: {len(missing)} Viser joints not found in saved dof_names; filling them with 0.")

        def _map(q_isaac: np.ndarray) -> np.ndarray:
            cfg = np.zeros(len(viser_joint_names), dtype=np.float64)
            for viser_idx, joint_name in enumerate(viser_joint_names):
                saved_idx = saved_name_to_idx.get(joint_name)
                if saved_idx is not None and saved_idx < q_isaac.shape[0]:
                    cfg[viser_idx] = q_isaac[saved_idx]
            return cfg

        return _map

    if len(viser_joint_names) == 32:
        def _map(q_isaac: np.ndarray) -> np.ndarray:
            if q_isaac.shape[0] == 32:
                return q_isaac[ISAAC_TO_VISER_IDX]
            if q_isaac.shape[0] == len(viser_joint_names):
                return q_isaac
            raise ValueError(f"Cannot map robot q shape {q_isaac.shape} to {len(viser_joint_names)} Viser joints.")

        return _map

    def _map(q_isaac: np.ndarray) -> np.ndarray:
        if q_isaac.shape[0] != len(viser_joint_names):
            raise ValueError(f"Cannot map robot q shape {q_isaac.shape} to {len(viser_joint_names)} Viser joints.")
        return q_isaac

    return _map


def get_num_frames(demo: ReplayDemo) -> int:
    num_frames = min(demo.robot_joint_position.shape[0], demo.object_pose.shape[0])
    if num_frames <= 0:
        raise RuntimeError("Trajectory contains no frames.")
    return int(num_frames)


def remove_handles(handles: list[object]) -> None:
    while handles:
        handle = handles.pop()
        try:
            handle.remove()
        except AttributeError:
            pass


def create_viewer(
    hdf5_path: Path,
    initial_demo: str,
    robot_urdf_override: Optional[str],
    host: str,
    port: int,
    show_paths: bool,
    show_world_axes: bool,
    show_eef_frame: bool,
    show_compartment_frame: bool,
) -> None:
    hdf5_path = hdf5_path.expanduser().resolve()
    demo_keys = list_demo_keys(hdf5_path)
    initial_demo_idx = resolve_demo_index(demo_keys, initial_demo)
    demo = load_replay_demo(hdf5_path, demo_keys[initial_demo_idx], robot_urdf_override)
    num_frames = get_num_frames(demo)

    server = viser.ViserServer(host=host, port=port)
    server.gui.configure_theme(control_width="medium")
    if show_world_axes:
        # CODEX: World axes are useful for debugging, but hidden by default for cleaner replay.
        server.scene.add_frame("/WorldAxes", show_axes=True, axes_length=0.25, axes_radius=0.01)
    server.scene.add_grid("/grid", width=6.0, height=6.0, position=(0.0, 0.0, 0.0), shadow_opacity=0.15)

    server.scene.add_frame("/robot", show_axes=False)
    robot_urdf = ViserUrdf(
        server,
        urdf_or_path=demo.robot_urdf_path,
        root_node_name="/robot",
        load_meshes=True,
        load_collision_meshes=False,
    )
    robot_joint_names = robot_urdf.get_actuated_joint_names()
    map_robot_cfg = build_robot_cfg_mapper(robot_joint_names, demo.robot_dof_names)

    object_root = server.scene.add_frame("/object", show_axes=False)

    demo_index_handle = server.gui.add_number(
        "Demo",
        initial_value=float(initial_demo_idx),
        min=0.0,
        max=float(len(demo_keys) - 1),
        step=1.0,
    )
    previous_demo_button = server.gui.add_button("Previous Demo")
    next_demo_button = server.gui.add_button("Next Demo")
    frame_slider = server.gui.add_slider(
        "Frame",
        min=0,
        max=max(num_frames - 1, 1),
        step=1,
        initial_value=0,
        disabled=(num_frames == 1),
    )
    speed_handle = server.gui.add_number("Speed", initial_value=1.0, min=0.1, max=10.0, step=0.1)
    loop_handle = server.gui.add_checkbox("Loop", initial_value=False)
    replay_button = server.gui.add_button("Replay")

    frame_lock = threading.RLock()
    replay_lock = threading.Lock()
    state = {
        "demo": demo,
        "demo_idx": initial_demo_idx,
        "num_frames": num_frames,
        "map_robot_cfg": map_robot_cfg,
        "scene_handles": [],
        "object_handles": [],
        "object_urdf": None,
        "eef_frame": None,
        "object_source": "",
        "generation": 0,
        "loading_demo": False,
        "playing": False,
        "setting_frame_slider": False,
        "robot_urdf_path": demo.robot_urdf_path,
    }

    def update_demo_buttons() -> None:
        demo_idx = int(state["demo_idx"])
        previous_demo_button.disabled = demo_idx <= 0
        next_demo_button.disabled = demo_idx >= len(demo_keys) - 1

    def set_playing(playing: bool) -> None:
        # CODEX: Keep the replay button itself as the play/pause toggle.
        state["playing"] = bool(playing)
        replay_button.label = "Pause" if bool(state["playing"]) else "Replay"

    def pause_replay() -> None:
        if bool(state["playing"]):
            set_playing(False)

    def set_frame_slider_value(frame_idx: int) -> None:
        state["setting_frame_slider"] = True
        try:
            frame_slider.value = int(frame_idx)
        finally:
            state["setting_frame_slider"] = False

    def reload_dynamic_scene() -> None:
        demo = state["demo"]
        num_frames = int(state["num_frames"])

        remove_handles(state["scene_handles"])
        remove_handles(state["object_handles"])
        object_urdf = state["object_urdf"]
        if object_urdf is not None:
            object_urdf.remove()
            state["object_urdf"] = None

        if demo.object_mesh_path is not None:
            # CODEX: Prefer direct mesh rendering so the object can be colored consistently.
            object_mesh = load_trimesh_mesh(demo.object_mesh_path, demo.object_scale)
            state["object_handles"].append(server.scene.add_mesh_trimesh("/object/mesh", mesh=object_mesh))
            object_source = f"mesh: {demo.object_mesh_path}"
        elif demo.object_urdf_path is not None:
            state["object_urdf"] = ViserUrdf(
                server,
                urdf_or_path=demo.object_urdf_path,
                root_node_name="/object",
                load_meshes=True,
                load_collision_meshes=False,
            )
            object_source = f"URDF: {demo.object_urdf_path}"
        else:
            state["object_handles"].append(
                server.scene.add_icosphere("/object/placeholder", radius=0.025, color=OBJECT_PLACEHOLDER_RGB)
            )
            object_source = "placeholder: object_info mesh path was unavailable"

        state["scene_handles"].extend(add_cuboid_obstacles(server, demo))
        state["scene_handles"].extend(add_compartment_state(server, demo, show_compartment_frame))
        if show_paths:
            # CODEX: Trajectory polylines are hidden by default; enable with --show-paths.
            object_path = add_polyline(
                server,
                "/paths/object_center",
                demo.object_pose[:num_frames, :3],
                (235, 120, 40),
                2.0,
            )
            if object_path is not None:
                state["scene_handles"].append(object_path)

        if show_paths and demo.robot_eef_pose is not None:
            eef_path = add_polyline(
                server,
                "/paths/eef",
                demo.robot_eef_pose[:num_frames, :3],
                (40, 120, 240),
                2.0,
            )
            if eef_path is not None:
                state["scene_handles"].append(eef_path)

        if show_eef_frame and demo.robot_eef_pose is not None:
            # CODEX: EEF axes are useful for pose debugging, but hidden by default.
            eef_frame = server.scene.add_frame("/eef", show_axes=True, axes_length=0.08, axes_radius=0.004)
            state["scene_handles"].append(eef_frame)
            state["eef_frame"] = eef_frame
        else:
            state["eef_frame"] = None

        state["object_source"] = object_source

    def update_frame(frame_idx: int, update_slider: bool = True) -> None:
        with frame_lock:
            demo = state["demo"]
            num_frames = int(state["num_frames"])
            frame_idx = int(np.clip(frame_idx, 0, num_frames - 1))
            robot_urdf.update_cfg(state["map_robot_cfg"](demo.robot_joint_position[frame_idx]))

            object_pose = demo.object_pose[frame_idx]
            object_root.position = tuple(float(v) for v in object_pose[:3])
            object_root.wxyz = xyzw_to_wxyz(object_pose[3:7])

            eef_frame = state["eef_frame"]
            if eef_frame is not None and demo.robot_eef_pose is not None:
                eef_pose = demo.robot_eef_pose[frame_idx]
                eef_frame.position = tuple(float(v) for v in eef_pose[:3])
                eef_frame.wxyz = xyzw_to_wxyz(eef_pose[3:7])

            if update_slider and int(frame_slider.value) != frame_idx:
                set_frame_slider_value(frame_idx)

    def load_demo_by_index(new_demo_idx: int) -> None:
        pause_replay()
        new_demo_idx = int(np.clip(new_demo_idx, 0, len(demo_keys) - 1))
        if new_demo_idx == int(state["demo_idx"]):
            state["loading_demo"] = True
            try:
                demo_index_handle.value = float(new_demo_idx)
            finally:
                state["loading_demo"] = False
            update_demo_buttons()
            return

        new_demo = load_replay_demo(hdf5_path, demo_keys[new_demo_idx], robot_urdf_override)
        new_num_frames = get_num_frames(new_demo)
        if new_demo.robot_urdf_path != state["robot_urdf_path"]:
            print(
                "Warning: selected demo has a different robot URDF; "
                f"continuing with {state['robot_urdf_path']}."
            )

        with frame_lock:
            state["generation"] = int(state["generation"]) + 1
            state["demo"] = new_demo
            state["demo_idx"] = new_demo_idx
            state["num_frames"] = new_num_frames
            state["map_robot_cfg"] = build_robot_cfg_mapper(robot_joint_names, new_demo.robot_dof_names)
            reload_dynamic_scene()

            frame_slider.max = max(new_num_frames - 1, 1)
            frame_slider.disabled = new_num_frames == 1
            state["loading_demo"] = True
            try:
                demo_index_handle.value = float(new_demo_idx)
                set_frame_slider_value(0)
            finally:
                state["loading_demo"] = False
            update_demo_buttons()
            update_frame(0, update_slider=False)

        print(
            f"Loaded {new_demo.demo_key} ({new_demo_idx + 1}/{len(demo_keys)}), "
            f"frames={new_num_frames}, object source: {state['object_source']}"
        )

    @demo_index_handle.on_update
    def _(_) -> None:
        if bool(state["loading_demo"]):
            return
        load_demo_by_index(int(round(float(demo_index_handle.value))))

    @previous_demo_button.on_click
    def _(_) -> None:
        load_demo_by_index(int(state["demo_idx"]) - 1)

    @next_demo_button.on_click
    def _(_) -> None:
        load_demo_by_index(int(state["demo_idx"]) + 1)

    @frame_slider.on_update
    def _(_) -> None:
        if not bool(state["setting_frame_slider"]):
            pause_replay()
        update_frame(int(frame_slider.value), update_slider=False)

    def replay_once() -> None:
        with replay_lock:
            generation = int(state["generation"])
            frame_cursor = float(frame_slider.value)
            last_time = time.monotonic()
            while bool(state["playing"]):
                if generation != int(state["generation"]):
                    set_playing(False)
                    return

                num_frames = int(state["num_frames"])
                now = time.monotonic()
                elapsed = now - last_time
                last_time = now
                frame_cursor += (
                    elapsed
                    * max(float(speed_handle.value), 0.01)
                    / DEFAULT_SECONDS_PER_FRAME
                )

                if frame_cursor >= num_frames:
                    if bool(loop_handle.value):
                        frame_cursor %= max(float(num_frames), 1.0)
                    else:
                        if int(frame_slider.value) != num_frames - 1:
                            update_frame(num_frames - 1)
                        set_playing(False)
                        return

                frame_idx = int(np.clip(frame_cursor, 0, num_frames - 1))
                if frame_idx == int(frame_slider.value):
                    time.sleep(PLAYBACK_POLL_SECONDS)
                    continue
                update_frame(frame_idx)
                time.sleep(PLAYBACK_POLL_SECONDS)

    @replay_button.on_click
    def _(_) -> None:
        if bool(state["playing"]):
            pause_replay()
            return
        if int(frame_slider.value) >= int(state["num_frames"]) - 1:
            update_frame(0)
        set_playing(True)
        thread = threading.Thread(target=replay_once, name="ViserReplay", daemon=True)
        thread.start()

    @server.on_client_connect
    def _(client: viser.ClientHandle) -> None:
        client.camera.position = (-1.4, -1.4, 1.0)
        client.camera.look_at = (0.3, 0.0, 0.35)

    reload_dynamic_scene()
    update_demo_buttons()
    update_frame(0)
    print(f"Viser replay server: http://{host}:{port}")
    print(f"HDF5: {hdf5_path}")
    print(f"Demo: {demo.demo_key} ({initial_demo_idx + 1}/{len(demo_keys)}), frames={num_frames}")
    print(f"Robot URDF: {demo.robot_urdf_path}")
    print(f"Object source: {state['object_source']}")
    print("Use 'Previous Demo'/'Next Demo' to switch demos, then click 'Replay' to play the trajectory.")

    while True:
        time.sleep(10.0)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Replay a saved robot/object trajectory HDF5 in Viser.")
    parser.add_argument("hdf5_path", type=Path, help="Trajectory HDF5 generated by the presampling script.")
    parser.add_argument("--demo", default="0", help="Demo index or key, e.g. 0 or demo_0.")
    parser.add_argument("--host", default="0.0.0.0", help="Viser server host.")
    parser.add_argument("--port", type=int, default=8080, help="Viser server port.")
    parser.add_argument("--robot-urdf", default=None, help="Optional robot URDF path override.")
    parser.add_argument("--show-paths", action="store_true", help="Show object and EEF trajectory polylines.")
    parser.add_argument("--show-world-axes", action="store_true", help="Show the world coordinate axes.")
    parser.add_argument("--show-eef-frame", action="store_true", help="Show the live EEF coordinate frame.")
    parser.add_argument(
        "--show-compartment-frame",
        action="store_true",
        help="Show the compartment coordinate frame.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    create_viewer(
        args.hdf5_path,
        initial_demo=args.demo,
        robot_urdf_override=args.robot_urdf,
        host=args.host,
        port=args.port,
        show_paths=args.show_paths,
        show_world_axes=args.show_world_axes,
        show_eef_frame=args.show_eef_frame,
        show_compartment_frame=args.show_compartment_frame,
    )


if __name__ == "__main__":
    main()
